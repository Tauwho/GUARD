#!/bin/bash
# Build the GUARD QSTI image (B-9, #43). Run on the QNX host with the SDP env sourced.
#   image/build-image.sh [--net user|bridge] [--test]
#     --net user    (default) DHCP for QEMU user-mode networking, no sudo (docs/setup.md Option C)
#     --net bridge  static 10.10.10.2 on br0 (docs/setup.md Option B)
#     --test        also add guard-hog (test image only, fault F2)
#     --secpol develop|secure
#                   develop: secpol records a policy (image/secpol/generate.sh)
#                   secure:  enforce image/secpol/guard.secpol (#46, D22)
# Builds every qnx/<process> project that exists, adds the binaries to /system/bin, adds the
# GUARD uids 1101-1106 and the start order (image/mkqnximage/snippets). Everything it writes
# goes under image/out/ (git-ignored). Nothing from the SDP is copied into the repo.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=$ROOT/image/out
NET=user
TEST=0
SECPOL=
while [ $# -gt 0 ]; do
    case $1 in
        --net) NET=$2; shift 2 ;;
        --test) TEST=1; shift ;;
        --secpol) SECPOL=$2; shift 2 ;;
        *) echo "usage: $0 [--net user|bridge] [--test] [--secpol develop|secure]" >&2; exit 2 ;;
    esac
done
[ "$NET" = user ] || [ "$NET" = bridge ] || { echo "--net must be user or bridge" >&2; exit 2; }
: "${QNX_HOST:?source qnxsdp-env.sh first}"
KEY=$HOME/.ssh/guard_target_ed25519
[ -f "$KEY" ] || ssh-keygen -q -t ed25519 -N '' -f "$KEY"

mkdir -p "$OUT/extra/snippets" "$OUT/build" "$OUT/qsti"
cp "$ROOT"/image/mkqnximage/snippets/*.guard "$OUT/extra/snippets/"
FILES=$OUT/extra/snippets/system_files.guard
echo "# generated by image/build-image.sh" > "$FILES"

# process directory : executable
PROCS="sim:guard-sim gate:guard-gate supervisor:guard-supervisor planner:guard-planner"
PROCS="$PROCS guardctl:guardctl bridge:guard-bridge"
[ "$TEST" = 1 ] && PROCS="$PROCS hog:guard-hog"
for entry in $PROCS; do
    dir=${entry%%:*} exe=${entry##*:}
    if [ ! -f "$ROOT/qnx/$dir/CMakeLists.txt" ]; then
        echo "skip $exe: qnx/$dir not in the repo yet"
        continue
    fi
    cmake -S "$ROOT/qnx/$dir" -B "$OUT/build/$dir" -G Ninja \
        -DCMAKE_TOOLCHAIN_FILE="$ROOT/cmake/qnx-x86_64.cmake" > "$OUT/build/$dir.log" 2>&1
    cmake --build "$OUT/build/$dir" --target "$exe" >> "$OUT/build/$dir.log" 2>&1 \
        || { echo "build of $exe failed, see $OUT/build/$dir.log" >&2; exit 1; }
    echo "[perms=555] bin/$exe=$OUT/build/$dir/$exe" >> "$FILES"
    echo "add  $exe"
done

# Normalized inputs (#141, INTERFACES.md I5): validated JSON-subset YAML from the host step,
# packed read-only under /system/guard/scenarios with the same layout as scenarios/.
INPUTS=$OUT/inputs
rm -rf "$INPUTS"
python3 "$ROOT/host/prepare_inputs.py" --out "$INPUTS" > "$OUT/inputs.log" 2>&1 \
    || { cat "$OUT/inputs.log" >&2; exit 1; }
python3 - "$INPUTS" <<'EOF' || { echo "inputs.json hash mismatch" >&2; exit 1; }
import hashlib, json, pathlib, sys
root = pathlib.Path(sys.argv[1])
manifest = json.loads((root / "inputs.json").read_text())
files = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}
bad = [p for p, h in manifest.items() if hashlib.sha256((root / p).read_bytes()).hexdigest() != h]
# Every packed file is listed, and nothing listed is missing.
sys.exit(1 if bad or not manifest or files != set(manifest) | {"inputs.json"} else 0)
EOF
(cd "$INPUTS" && find . -type f | sort) | while read -r f; do
    echo "[perms=444] guard/scenarios/${f#./}=$INPUTS/${f#./}" >> "$FILES"
done
echo "add  $(grep -c guard/scenarios "$FILES") input files (inputs.json hashes match)"
echo "[perms=555] bin/guard-inputs-check=$ROOT/image/inputs-check.sh" >> "$FILES"
# Test image: traceprinter from the SDP decodes tracelogger output on the target (#48). It is
# copied into the image only, never into the repo.
if [ "$TEST" = 1 ]; then
    echo "[perms=555] bin/traceprinter=$QNX_TARGET/x86_64/usr/bin/traceprinter" >> "$FILES"
    echo "[perms=555] bin/guard-trace-check=$ROOT/image/trace-check.sh" >> "$FILES"
fi

SECPOL_ARGS=()
case $SECPOL in
    "") SECPOL_ARGS=(--secpol=no --policy=none) ;; # mkqnximage keeps the last choice otherwise
    develop) SECPOL_ARGS=(--secpol=develop --policy=none) ;;
    secure)
        [ -f "$ROOT/image/secpol/guard.secpol" ] || { echo "no image/secpol/guard.secpol; run image/secpol/generate.sh" >&2; exit 1; }
        SECPOL_ARGS=(--secpol=secure "--policy=$ROOT/image/secpol/guard.secpol") ;;
    *) echo "--secpol must be develop or secure" >&2; exit 2 ;;
esac

if [ -n "$SECPOL" ]; then
    echo "$SECPOL" > "$OUT/extra/guard-secpol"
    echo "[perms=444] etc/guard-secpol=$OUT/extra/guard-secpol" >> "$FILES"
fi

IP=dhcp
[ "$NET" = bridge ] && IP=10.10.10.2
cd "$OUT/qsti"
mkqnximage --type=qemu --arch=x86_64 --hostname=guard --ip="$IP" --sshd-pregen=yes \
    --ssh-ident="$KEY.pub" --extra-dirs="$OUT/extra" "${SECPOL_ARGS[@]}" --noprompt --build > "$OUT/mkqnximage.log" 2>&1 \
    || { tail -20 "$OUT/mkqnximage.log" >&2; exit 1; }
echo "image built in $OUT/qsti (network: $NET${SECPOL:+, secpol: $SECPOL})"
